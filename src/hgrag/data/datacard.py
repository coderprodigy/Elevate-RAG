"""Data cards: size and composition of each processed dataset (feeds report section 4a)."""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence

from pydantic import BaseModel

from hgrag.config import DatasetSettings
from hgrag.data.schema import Document, Query

_CHARS_PER_TOKEN = 4  # rough English average; real token counts come with chunking (Phase 3)


class DataCard(BaseModel):
    name: str
    source_url: str
    license: str
    n_documents: int
    n_queries: int
    n_dev: int
    n_test: int
    n_unanswerable: int
    approx_corpus_tokens: int
    mean_doc_tokens: float
    by_type: dict[str, dict[str, int]]  # query_type → {"dev": n, "test": n}
    notes: list[str]


def compute_datacard(
    name: str,
    settings: DatasetSettings,
    documents: Sequence[Document],
    queries: Sequence[Query],
    notes: Sequence[str],
) -> DataCard:
    total_tokens = sum(len(d.text) for d in documents) // _CHARS_PER_TOKEN
    splits = Counter(q.split for q in queries)
    by_type: dict[str, dict[str, int]] = {}
    for query in queries:
        counts = by_type.setdefault(query.query_type, {"dev": 0, "test": 0})
        if query.split is not None:
            counts[query.split] += 1
    return DataCard(
        name=name,
        source_url=settings.source_url,
        license=settings.license,
        n_documents=len(documents),
        n_queries=len(queries),
        n_dev=splits["dev"],
        n_test=splits["test"],
        n_unanswerable=sum(not q.answerable for q in queries),
        approx_corpus_tokens=total_tokens,
        mean_doc_tokens=round(total_tokens / len(documents), 1) if documents else 0.0,
        by_type=dict(sorted(by_type.items())),
        notes=list(notes),
    )


def render_markdown(cards: Sequence[DataCard]) -> str:
    """One summary table across datasets, then a query-type breakdown per dataset."""
    lines = [
        "# Data cards",
        "",
        "Generated by `hgrag data card`. Token counts are estimates (characters / 4).",
        "",
        "| Dataset | Docs | ~Corpus tokens | Queries | Dev | Test | Unanswerable | Licence |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for c in cards:
        lines.append(
            f"| {c.name} | {c.n_documents:,} | {c.approx_corpus_tokens:,} | {c.n_queries:,} "
            f"| {c.n_dev:,} | {c.n_test:,} | {c.n_unanswerable:,} | {c.license} |"
        )
    for c in cards:
        lines += ["", f"## {c.name}", "", f"Source: {c.source_url}", ""]
        lines += ["| Query type | Dev | Test |", "|---|---:|---:|"]
        lines += [f"| {t} | {n['dev']} | {n['test']} |" for t, n in c.by_type.items()]
        if c.notes:
            lines += ["", *[f"- {note}" for note in c.notes]]
    return "\n".join(lines) + "\n"
